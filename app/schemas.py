# Request size limits. String limits match the database columns they are stored in, so an
# oversized value is a 422 here instead of a 500 from the database. Free text stored in Text
# columns and free-form JSON get generous but finite limits.
ID_LEN = 64  # String(64) primary keys
NAME_LEN = 255  # String(255) names, titles, emails
SHORT_LEN = 32  # String(32) roles, statuses, plans, decisions
TEXT_LEN = 20_000  # Text descriptions and conditions
PROMPT_LEN = 100_000  # run input
SECRET_LEN = 8_192  # bearer tokens, API keys
PASSWORD_LEN = 1_024  # hashing cost grows with input; nobody needs more
CODE_LEN = 64  # one-time codes
TOKEN_LEN = 512  # invite tokens, challenges
URL_LEN = 512  # String(512) endpoints
LOCALE_LEN = 35  # BCP 47 tag
ID_LIST_LEN = 500
JSON_SMALL = 16 * 1024
JSON_MEDIUM = 64 * 1024
JSON_LARGE = 256 * 1024


def _json_limit(max_bytes: int):
    def check(value):
        if value is None:
            return value
        try:
            size = len(json.dumps(value, separators=(",", ":"), default=str).encode("utf-8"))
        except (TypeError, ValueError) as exc:
            raise ValueError("Value must be JSON") from exc
        if size > max_bytes:
            raise ValueError(f"Value is too large (limit {max_bytes} bytes as JSON)")
        return value

    return AfterValidator(check)


Id = Annotated[str, Field(max_length=ID_LEN)]
IdList = Annotated[list[Id], Field(max_length=ID_LIST_LEN)]
SmallJson = Annotated[Any, _json_limit(JSON_SMALL)]
MediumDict = Annotated[dict[str, Any], _json_limit(JSON_MEDIUM)]
LargeDict = Annotated[dict[str, Any], _json_limit(JSON_LARGE)]


